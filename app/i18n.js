let current = 'en';

export function setLang(value) {
  current = value === 'es' ? 'es' : 'en';
  return current;
}

export const lang = () => current;

/** The first of the browser's languages that the app speaks, "es" or "en"; English when it speaks none of them. */
export function langForBrowser(languages) {
  for (const tag of languages || []) {
    const primary = String(tag).toLowerCase().split('-')[0];
    if (primary === 'es' || primary === 'en') return primary;
  }
  return 'en';
}

/** The browser's own variant of the interface language for dates and numbers, such as en-GB or es-MX. */
export function locale() {
  const own = (globalThis.navigator?.languages || []).find(l => l.toLowerCase().split('-')[0] === current);
  return own || current;
}

export const fmt = n => intl(Intl.NumberFormat).format(Number(n || 0));

const formatters = new Map();
/** A formatter in the interface language, made once per kind and options: making one is slow, and every row uses some. */
export function intl(Type, options = {}) {
  const key = `${Type.name} ${locale()} ${JSON.stringify(options)}`;
  if (!formatters.has(key)) formatters.set(key, new Type(locale(), options));
  return formatters.get(key);
}

/** The text for a key, with {0}, {1}... filled in. */
export function t(key, ...params) {
  const template = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\d+)\}/g, (m, i) => String(params[i] ?? m));
}

/** A text that says a count: the key's ".one" form for 1, its ".other" form for the rest, with the count as {0}. */
export const tn = (key, n, ...params) => t(`${key}.${n === 1 ? 'one' : 'other'}`, fmt(n), ...params);

/** The word for `n` of something, such as "mails". */
export const noun = (key, n) => (NOUNS[current][key] || NOUNS.en[key] || [key, key])[n === 1 ? 0 : 1];

// The English of each translated element, kept from the page as it was first loaded.
const originals = new WeakMap();
const ATTRIBUTES = [['aria-label', 'i18nAriaLabel'], ['title', 'i18nTitle'], ['placeholder', 'i18nPlaceholder']];

function original(el, what) {
  let kept = originals.get(el);
  if (!kept) originals.set(el, (kept = {}));
  if (!(what in kept)) kept[what] = what === 'html' ? el.innerHTML : el.getAttribute(what);
  return kept[what];
}

/** Puts the page's own texts in the interface language. The translations are this file's constants, never data. */
export function translatePage(doc) {
  doc.documentElement.lang = current;
  for (const el of doc.querySelectorAll('[data-i18n]')) {
    const english = original(el, 'html');
    el.innerHTML = current === 'es' ? PAGE_ES[el.dataset.i18n] ?? english : english;
  }
  for (const [attribute, key] of ATTRIBUTES) {
    for (const el of doc.querySelectorAll(`[data-i18n-${attribute}]`)) {
      const english = original(el, attribute);
      el.setAttribute(attribute, current === 'es' ? PAGE_ES[el.dataset[key]] ?? english : english);
    }
  }
}

export { STRINGS, NOUNS, PAGE_ES };
